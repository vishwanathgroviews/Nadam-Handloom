#!/usr/bin/env python3
"""Builds the W5 bag mock-up's data and copies the live website's look into it.

What it does (run from anywhere; standard library only):
  1. Reads real sarees from the new server's public website API (/api/v2/shop): a few
     single pieces, sets and one sold-out saree, plus the shop's details and the catalogue
     totals. Default: a local server on the 16 Oct copy of live data (port 4300).
  2. Downloads each saree's first photo into ../img/ (named by its code).
  3. Writes ../assets/data.js (window.W5DATA).
  4. Copies the website's styles, fonts, icons and logo from Nadam-frontend/customer-web, so
     the mock-up looks exactly like the live site (nothing in them is changed).

  python3 build-data.py [--api http://127.0.0.1:4300/api/v2/shop]
"""
import argparse, json, os, re, shutil, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
MOCK = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(MOCK, '..', '..', '..', '..'))  # Nadam-Handloom-production
WEB = os.path.join(ROOT, 'Nadam-frontend', 'customer-web')

# Real listings picked for the mock-up (16 Oct 2026). Singles come from these collections
# (first single piece with a photo); sets and the sold-out saree are fixed links.
SINGLE_COLLECTIONS = ['578a9407', '4eb1ce5b', '60301a95', '34f68ec3', '1b5262fc', 'a1956ab4', '8cabe3f4']
SETS = ['50-50-digital-print-34', '150-50-plain-saree-7', 'gap-border-embroidery-sarees-19', '300k-plain-saree-9']
SOLD = ['350k-butta-saree-3']


def get(api, path):
    req = urllib.request.Request(api + path, headers={'Accept': 'application/json'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def slim(p, kind):
    return {
        'slug': p['slug'], 'sku': p['sku'], 'name': p['name'],
        'collection': p['collection'], 'category': p['category'] if isinstance(p['category'], dict) else {'slug': p['category'], 'name': ''},
        'craftName': p.get('craftName'), 'price': p['price'], 'available': p['available'], 'soldOut': p.get('soldOut', p['available'] < 1),
        'isNew': p.get('isNew', False), 'description': p.get('description', ''), 'highlights': p.get('highlights', []),
        'photoUrl': (p.get('photo') or {}).get('url'), 'photoAlt': (p.get('photo') or {}).get('alt', p['name']), 'kind': kind,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--api', default='http://127.0.0.1:4300/api/v2/shop')
    a = ap.parse_args()

    config = get(a.api, '/config')
    catalog = get(a.api, '/catalog')
    cols = {c['id'][:8]: c for c in catalog['collections']}
    slugs = []
    for pre in SINGLE_COLLECTIONS:
        lst = get(a.api, '/products?' + urllib.parse.urlencode({'collection': cols[pre]['id'], 'offset': 0, 'limit': 12}))
        pick = next(x for x in lst['items'] if x['available'] == 1 and x['photo'])
        slugs.append((pick['slug'], 'single'))
    slugs += [(s, 'set') for s in SETS] + [(s, 'sold') for s in SOLD]

    os.makedirs(os.path.join(MOCK, 'img'), exist_ok=True)
    sarees = []
    for slug, kind in slugs:
        p = slim(get(a.api, '/products/' + slug)['product'], kind)
        if p['photoUrl']:
            name = re.sub(r'[^A-Za-z0-9-]', '', p['sku']) + '.jpg'
            dest = os.path.join(MOCK, 'img', name)
            if not os.path.exists(dest):
                urllib.request.urlretrieve(p['photoUrl'], dest)
            p['photo'] = 'img/' + name
        sarees.append(p)
        print(kind.ljust(6), p['sku'], p['name'], p['price'], 'in stock', p['available'])

    data = {
        'builtFrom': 'Live data copy of 16 Oct 2026 (local server ' + a.api + ')',
        'shop': config['shop'], 'store': config['store'],
        'totals': catalog['totals'],
        'categories': [{'slug': c['slug'], 'name': c['name'], 'count': c.get('count')} for c in catalog['categories']],
        'sarees': sarees,
    }
    with open(os.path.join(MOCK, 'assets', 'data.js'), 'w') as f:
        f.write('/* Generated by build/build-data.py. Real sarees, prices and codes from the live data of 16 Oct 2026. */\n')
        f.write('window.W5DATA = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')

    # The live website's look, copied unchanged.
    css = os.path.join(MOCK, 'assets', 'site')
    os.makedirs(css, exist_ok=True)
    for n in ['tokens.css', 'base.css', 'pages.css', 'shop.css']:
        shutil.copy(os.path.join(WEB, 'src', 'theme', n), os.path.join(css, n))
    fonts = os.path.join(MOCK, 'assets', 'fonts')
    os.makedirs(fonts, exist_ok=True)
    nm = os.path.join(WEB, 'node_modules')
    for src in ['@fontsource/bodoni-moda/files/bodoni-moda-latin-400-normal.woff2', '@fontsource/bodoni-moda/files/bodoni-moda-latin-500-normal.woff2',
                '@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2']:
        shutil.copy(os.path.join(nm, src), fonts)
    icons = open(os.path.join(WEB, 'src', 'components', 'icons.js')).read()
    icons = icons.replace('export const ICONS =', 'window.ICONS =')
    with open(os.path.join(MOCK, 'assets', 'icons.js'), 'w') as f:
        f.write('/* Copied from Nadam-frontend/customer-web/src/components/icons.js by build/build-data.py. */\n' + icons)
    shutil.copy(os.path.join(WEB, 'public', 'img', 'logo-96.png'), os.path.join(MOCK, 'img', 'logo-96.png'))
    for n in ['loom-800.jpg']:
        shutil.copy(os.path.join(WEB, 'public', 'img', 'site', n), os.path.join(MOCK, 'img', n))
    print('done:', len(sarees), 'sarees')


if __name__ == '__main__':
    main()
